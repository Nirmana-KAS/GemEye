// Public certificate verification (/v/?c={cert}-{token} or /v/{cert}-{token}).
// Pure helpers, unit tested in tests/verify.test.ts.

export interface PublicColour {
  L?: number;
  a?: number;
  b?: number;
  C?: number;
  H?: number;
  S?: number;
  B?: number;
  hex?: string;
  approximate?: boolean;
}

export interface PublicSnapshot {
  stone_id?: string;
  grade?: number;
  grade_name?: string;
  trade_name?: string;
  confidence?: number;
  uncertainty?: number;
  referred?: boolean;
  colour?: PublicColour | null;
  delta_e00_to_typical?: number | null;
  model_version?: string;
  captured_at?: string;
  issued_at?: string;
}

/** GET /public/v/{slug}. Never contains the owner's uid or email. */
export interface PublicCertificate {
  cert_no: string;
  status: "valid" | "revoked" | "withdrawn";
  issued_at: string;
  snapshot?: PublicSnapshot | null;
  owner?: { display_name?: string | null; company?: string | null } | null;
  revoked_reason?: string | null;
  revoked_at?: string | null;
  superseded_by?: string | null;
  superseded_by_url?: string | null;
  review?: { gemologist_grade?: number | null; reviewed_at?: string } | null;
  image_url?: string | null;
  pdf_url?: string | null;
  pdf_sha256?: string | null;
  disclaimer: string;
}

export type VerifyState =
  | { kind: "valid"; cert: PublicCertificate }
  | { kind: "revoked"; cert: PublicCertificate }
  | { kind: "superseded"; cert: PublicCertificate }
  | { kind: "withdrawn"; cert: PublicCertificate }
  | { kind: "not_found" }
  | { kind: "unreachable"; rateLimited: boolean };

/** The same text as the app's PDF certificate (and the server's disclaimer). */
export const DISCLAIMER =
  "Generated by the GemEye automated colour grading system. Not a substitute for a certified gemological laboratory report.";

const SLUG = /^GE-\d{6}-\d{5}-[A-Za-z0-9_-]{4,64}$/;

/** The certificate slug from ?c= or from the path /v/{slug}/ (Firebase rewrite or a
 * redirect from the 404 page). Null when missing or malformed (shown as Not found). */
export function parseVerifySlug(pathname: string, search: string): string | null {
  const fromQuery = new URLSearchParams(search).get("c");
  let raw = fromQuery ?? "";
  if (!raw) {
    const m = /^\/v\/([^/?#]+)\/?$/.exec(pathname);
    raw = m ? m[1] : "";
  }
  try {
    raw = decodeURIComponent(raw).trim();
  } catch {
    return null;
  }
  return SLUG.test(raw) ? raw : null;
}

/** /v/?c={slug} for a path /v/{slug}[/] with a well-formed slug (the 404 page redirect). */
export function verifyRedirectTarget(pathname: string): string | null {
  if (!/^\/v\/[^/]+\/?$/.test(pathname)) return null;
  const slug = parseVerifySlug(pathname, "");
  return slug ? `/v/?c=${encodeURIComponent(slug)}` : null;
}

/** The certificate number part of a slug ("GE-202610-00042"). */
export function certNoOf(slug: string): string {
  return slug.split("-").slice(0, 3).join("-");
}

/** Maps the API answer to a page state. status 0 = network error (no answer). */
export function verifyStateFrom(status: number, body: unknown): VerifyState {
  if (status === 404 || status === 400 || status === 422) return { kind: "not_found" };
  if (status === 429) return { kind: "unreachable", rateLimited: true };
  if (status !== 200 || !body || typeof body !== "object") return { kind: "unreachable", rateLimited: false };
  const cert = body as PublicCertificate;
  if (cert.status === "withdrawn") return { kind: "withdrawn", cert };
  if (cert.status === "revoked") return cert.superseded_by ? { kind: "superseded", cert } : { kind: "revoked", cert };
  if (cert.status === "valid") return { kind: "valid", cert };
  return { kind: "unreachable", rateLimited: false };
}

/** Calls GET /public/v/{slug} (no login, no credentials). */
export async function fetchVerify(
  baseUrl: string,
  slug: string,
  fetchFn: typeof fetch = fetch,
): Promise<VerifyState> {
  let res: Response;
  try {
    res = await fetchFn(`${baseUrl}/public/v/${encodeURIComponent(slug)}`, {
      method: "GET",
      credentials: "omit",
      cache: "no-store",
      headers: { Accept: "application/json" },
    });
  } catch {
    return verifyStateFrom(0, null);
  }
  let body: unknown = null;
  try {
    body = await res.json();
  } catch {
    body = null;
  }
  return verifyStateFrom(res.status, body);
}

/** Lower-case hex SHA-256 of the bytes (Web Crypto, in the browser). */
export async function sha256Hex(data: ArrayBuffer | Uint8Array): Promise<string> {
  const bytes = data instanceof Uint8Array ? data : new Uint8Array(data);
  const digest = await crypto.subtle.digest("SHA-256", bytes as BufferSource);
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
}

/** True when both are the same 64-hex SHA-256 (case and spaces ignored). */
export function sameSha256(a: string | null | undefined, b: string | null | undefined): boolean {
  const norm = (s: string | null | undefined) => (s ?? "").trim().toLowerCase();
  const x = norm(a);
  return /^[0-9a-f]{64}$/.test(x) && x === norm(b);
}

/** "match" / "mismatch" for a file checked against the certificate's stored hash. */
export async function checkPdf(data: ArrayBuffer | Uint8Array, expected: string | null | undefined) {
  const actual = await sha256Hex(data);
  return { actual, match: sameSha256(actual, expected) };
}
